create or replace function public.place_leafora_order(
  p_customer_name text,
  p_customer_phone text,
  p_fulfillment text,
  p_delivery_address text,
  p_note text,
  p_items jsonb
)
returns table(order_id bigint, order_total numeric)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_products jsonb;
  v_line jsonb;
  v_product jsonb;
  v_product_id text;
  v_quantity integer;
  v_price numeric;
  v_total numeric := 0;
  v_items jsonb := '[]'::jsonb;
  v_seen text[] := array[]::text[];
  v_phone_digits text;
begin
  if pg_catalog.char_length(pg_catalog.btrim(coalesce(p_customer_name, ''))) not between 2 and 120 then
    raise exception using errcode = '22023', message = 'Please provide a valid customer name.';
  end if;
  v_phone_digits := pg_catalog.regexp_replace(coalesce(p_customer_phone, ''), '[^0-9]', '', 'g');
  if p_customer_phone !~ '^[+0-9() -]{7,25}$' or pg_catalog.char_length(v_phone_digits) not between 7 and 15 then
    raise exception using errcode = '22023', message = 'Please provide a valid phone number.';
  end if;
  if p_fulfillment is null or p_fulfillment not in ('delivery', 'pickup') then
    raise exception using errcode = '22023', message = 'Please select delivery or pickup.';
  end if;
  if p_fulfillment = 'delivery' and pg_catalog.char_length(pg_catalog.btrim(coalesce(p_delivery_address, ''))) = 0 then
    raise exception using errcode = '22023', message = 'A delivery address is required.';
  end if;
  if pg_catalog.char_length(coalesce(p_delivery_address, '')) > 500 or pg_catalog.char_length(coalesce(p_note, '')) > 500 then
    raise exception using errcode = '22023', message = 'Order details are too long.';
  end if;
  if coalesce(pg_catalog.jsonb_typeof(p_items), 'null') <> 'array' then
    raise exception using errcode = '22023', message = 'Your cart contents are invalid.';
  end if;
  if pg_catalog.jsonb_array_length(p_items) not between 1 and 20 then
    raise exception using errcode = '22023', message = 'Your cart is empty or has too many items.';
  end if;

  select content.data -> 'products' into v_products
  from public.site_content as content where content.id = 'main';
  if v_products is null or pg_catalog.jsonb_typeof(v_products) <> 'array' then
    raise exception using errcode = 'P0001', message = 'The product catalogue is unavailable.';
  end if;

  for v_line in select element from pg_catalog.jsonb_array_elements(p_items) as lines(element) loop
    v_product_id := v_line ->> 'product_id';
    if v_product_id is null or pg_catalog.char_length(v_product_id) > 100 then
      raise exception using errcode = '22023', message = 'A cart item is invalid.';
    end if;
    if v_product_id = any(v_seen) then
      raise exception using errcode = '22023', message = 'Duplicate cart items are not allowed.';
    end if;
    if coalesce(v_line ->> 'quantity', '') !~ '^[0-9]{1,2}$' then
      raise exception using errcode = '22023', message = 'A cart quantity is invalid.';
    end if;
    v_quantity := (v_line ->> 'quantity')::integer;
    if v_quantity not between 1 and 20 then
      raise exception using errcode = '22023', message = 'Cart quantities must be between 1 and 20.';
    end if;

    select element into v_product
    from pg_catalog.jsonb_array_elements(v_products) as catalogue(element)
    where element ->> 'id' = v_product_id
    limit 1;
    if v_product is null then
      raise exception using errcode = '22023', message = 'A selected product is no longer available.';
    end if;
    if coalesce(v_product ->> 'price', '') !~ '^[0-9]+([.][0-9]{1,2})?$' then
      raise exception using errcode = '22023', message = 'A product price is invalid.';
    end if;
    v_price := (v_product ->> 'price')::numeric;
    if v_price < 0 then
      raise exception using errcode = '22023', message = 'A product price is invalid.';
    end if;

    v_seen := pg_catalog.array_append(v_seen, v_product_id);
    v_total := v_total + v_price * v_quantity;
    v_items := v_items || pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'product_id', v_product_id,
      'name', v_product ->> 'name',
      'quantity', v_quantity,
      'unit_price', v_price,
      'subtotal', v_price * v_quantity
    ));
    v_product := null;
  end loop;
  if v_total <= 0 then
    raise exception using errcode = '22023', message = 'Your order total must be greater than zero.';
  end if;

  return query
  insert into public.orders (customer_name, customer_phone, fulfillment, delivery_address, note, items, total_amount)
  values (
    pg_catalog.btrim(p_customer_name),
    pg_catalog.btrim(p_customer_phone),
    p_fulfillment,
    case when p_fulfillment = 'delivery' then pg_catalog.btrim(p_delivery_address) else '' end,
    pg_catalog.btrim(coalesce(p_note, '')),
    v_items,
    v_total
  )
  returning id, total_amount;
end;
$$;

